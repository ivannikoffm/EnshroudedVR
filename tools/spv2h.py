"""Compile a GLSL compute shader with tools/glslang and emit a C header (uint32 array) for embedding in the DLL.
usage: python spv2h.py <in.comp> <out.h> <array_name>"""
import os, struct, subprocess, sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
GLSLANG = os.path.join(TOOLS, 'glslang', 'bin', 'glslang.exe')


def main(src, out, name):
    spv = out + '.spv'
    r = subprocess.run([GLSLANG, '-V', '--target-env', 'vulkan1.0', '-o', spv, src], capture_output=True, text=True)
    print(r.stdout.strip(), r.stderr.strip())
    if r.returncode:
        sys.exit(r.returncode)
    data = open(spv, 'rb').read()
    assert len(data) % 4 == 0 and data[:4] == b'\x03\x02\x23\x07', 'not SPIR-V'
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    lines = [', '.join('0x%08x' % w for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    with open(out, 'w') as f:
        f.write('// generated by tools/spv2h.py from %s - do not edit\n#pragma once\n#include <cstdint>\n' % os.path.basename(src))
        f.write('static const uint32_t %s[%d] = {\n    %s\n};\n' % (name, len(words), ',\n    '.join(lines)))
    print('%s: %d words (%d bytes)' % (out, len(words), len(data)))


if __name__ == '__main__':
    main(*sys.argv[1:4])
